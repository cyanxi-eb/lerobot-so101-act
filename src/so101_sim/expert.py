"""Scripted Cartesian expert + domain randomisation for demo generation.

The expert is a five-segment Cartesian state machine
``home -> approach -> grasp -> lift -> over box -> place -> retreat``.
Waypoints are converted with the analytic IK and linearly interpolated in
joint space; the gripper opens/closes on a schedule.  Because the initial
arm pose is randomised in every reset, the expert has to track back from an
unknown start pose, which is what makes the resulting demonstrations useful
for behaviour cloning.

No hardware teleoperation is involved: demonstrations are generated by this
script in the simulator.  See ``docs/real_robot.md`` for the real SO-101
teleoperation protocol this pipeline is meant to plug into.
"""

from __future__ import annotations

import numpy as np

from . import kinematics as kin
from .env import GraspEnv

#: (waypoint name, gripper target, number of interpolation steps)
SEGMENTS: tuple[tuple[str, float, int], ...] = (
    ("home", 1.0, 4),
    ("approach", 1.0, 10),
    ("grasp", 1.0, 7),
    ("grasp", 0.0, 5),
    ("lift", 0.0, 7),
    ("over_box", 0.0, 11),
    ("place", 0.0, 6),
    ("place", 1.0, 4),
    ("retreat", 1.0, 6),
)

TOTAL_STEPS = sum(seg[2] for seg in SEGMENTS)


def plan_expert_actions(env: GraspEnv) -> np.ndarray:
    """Return the scripted expert action sequence ``(TOTAL_STEPS, 6)``."""
    if env.scene is None:
        raise RuntimeError("environment must be reset before planning")
    waypoints = env.expert_waypoints()
    q_start = env.q.copy()
    q_targets = {name: kin.ik(pos) for name, pos in waypoints.items()}

    actions: list[np.ndarray] = []
    q_prev = q_start
    g_prev = float(env.opening)
    for name, grip_target, steps in SEGMENTS:
        q_next = q_targets[name]
        for i in range(1, steps + 1):
            frac = i / steps
            q_cmd = q_prev + (q_next - q_prev) * frac
            g_cmd = g_prev + (grip_target - g_prev) * frac
            actions.append(np.concatenate([q_cmd, [g_cmd]]))
        q_prev, g_prev = q_next, grip_target
    out = np.asarray(actions, dtype=np.float32)
    assert out.shape == (TOTAL_STEPS, kin.ACTION_DIM), out.shape
    return out


def rollout_expert(env: GraspEnv, max_steps: int | None = None) -> dict:
    """Execute the scripted expert and collect one fixed-length demonstration.

    Returns a dict with ``front`` (T,96,96,3), ``wrist`` (T,96,96,3),
    ``state`` (T,6), ``action`` (T,6), ``success``, ``failure`` and
    ``events``.  The rollout always runs for exactly ``T`` steps (the
    post-release retreat is part of the demonstration) so every episode in
    the dataset has the same length; ``success`` is sticky.
    """
    actions = plan_expert_actions(env)
    limit = int(max_steps if max_steps is not None else min(len(actions), env.config.max_steps))
    frames_front, frames_wrist, states, exec_actions = [], [], [], []
    obs = env._obs()
    success = False
    info: dict = {}
    for t in range(limit):
        frames_front.append(obs["front"])
        frames_wrist.append(obs["wrist"])
        states.append(obs["state"])
        exec_actions.append(actions[t])
        # env.step() renders the *next* observation, so each control step only
        # costs one render pass for the whole rollout.
        obs, _, _, info = env.step(actions[t])
        success = success or bool(info.get("success"))
    if env.scene is not None:
        info = env.info()
    return {
        "front": np.asarray(frames_front, dtype=np.uint8),
        "wrist": np.asarray(frames_wrist, dtype=np.uint8),
        "state": np.asarray(states, dtype=np.float32),
        "action": np.asarray(exec_actions, dtype=np.float32),
        "success": bool(success),
        "failure": info.get("failure"),
        "events": info.get("events", []),
        "scene": env.scene.meta() if env.scene is not None else None,
    }
